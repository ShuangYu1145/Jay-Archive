"""Generate Android strings and source-metadata lookup keys from the reviewed UI translations.

Run with Python 3: python scripts/localization/generate.py
No network access or extra dependencies are required.
"""
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
entries = json.loads((HERE / "ui.json").read_text(encoding="utf-8"))
FOLDERS = {"zh-Hans": "values", "zh-Hant": "values-b+zh+Hant", "en": "values-en", "ja": "values-ja", "ko": "values-ko"}

def android_text(value):
    return escape(value.replace("'", "\\'").replace('"', '\\"'))

for locale, folder in FOLDERS.items():
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated from scripts/localization/ui.json. -->', '<resources>']
    app_name = "傑作 · Jay Archive" if locale == "zh-Hant" else "杰作 · Jay Archive" if locale == "zh-Hans" else "Jay Archive"
    lines.append(f'    <string name="app_name">{app_name}</string>')
    for entry in entries:
        expected = sorted(re.findall(r'%\d+\$[sd]', entry['zh-Hans']))
        assert sorted(re.findall(r'%\d+\$[sd]', entry[locale])) == expected, (entry['key'], locale)
        lines.append(f'    <string name="{entry["key"]}">{android_text(entry[locale])}</string>')
        if 'countArg' in entry:
            one = entry.get('enOne', entry[locale]) if locale == 'en' else entry[locale]
            lines.append(f'    <plurals name="{entry["key"]}">')
            lines.append(f'        <item quantity="one">{android_text(one)}</item>')
            lines.append(f'        <item quantity="other">{android_text(entry[locale])}</item>')
            lines.append('    </plurals>')
    for kind, labels in {
        'album_count': {'zh-Hans': ('%1$d 张专辑',)*2, 'zh-Hant': ('%1$d 張專輯',)*2, 'en': ('%1$d album','%1$d albums'), 'ja': ('アルバム %1$d 件',)*2, 'ko': ('앨범 %1$d개',)*2},
        'song_count': {'zh-Hans': ('%1$d 首歌曲',)*2, 'zh-Hant': ('%1$d 首歌曲',)*2, 'en': ('%1$d song','%1$d songs'), 'ja': ('楽曲 %1$d 件',)*2, 'ko': ('노래 %1$d곡',)*2},
    }.items():
        one, other = labels[locale]
        lines.extend([f'    <plurals name="{kind}">', f'        <item quantity="one">{android_text(one)}</item>', f'        <item quantity="other">{android_text(other)}</item>', '    </plurals>'])
    lines.append('</resources>')
    path = ROOT / 'app/src/main/res' / folder / 'strings.xml'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    if locale == 'zh-Hans':
        explicit = ROOT / 'app/src/main/res/values-b+zh+Hans/strings.xml'
        explicit.parent.mkdir(parents=True, exist_ok=True)
        explicit.write_text('\n'.join(lines) + '\n', encoding='utf-8')

registry = []
for entry in entries:
    # Source text is a lookup key, never a translated value used in parsers or persisted state.
    key = json.dumps(entry['zh-Hans'], ensure_ascii=False).replace('$', '\\$')
    registry.append(f'    {key} to R.string.{entry["key"]}')
path = ROOT / 'app/src/main/java/love/yu/jaychou/data/OriginalTextKeys.kt'
path.write_text('package love.yu.jaychou.data\n\nimport love.yu.jaychou.R\n\n'
                '// Generated by scripts/localization/generate.py.\ninternal val originalTextKeys = mapOf(\n'
                + ',\n'.join(registry) + '\n)\n\ninternal val quantityTextKeys = mapOf(\n'
                + ',\n'.join(f'    R.string.{e["key"]} to (R.plurals.{e["key"]} to {e["countArg"]})' for e in entries if 'countArg' in e)
                + '\n)\n', encoding='utf-8')
print(f'Generated {len(entries)} resources in {len(FOLDERS)} languages; placeholders verified.')
